-- 成片 → 资产库素材包的回指。forward-only。
--
-- 起点是看板上那句「可入资产库 · 尚未入库」：成片列里哪些已经打包发布了、哪些还躺着，
-- 原先在库里**没有任何一处记着**。`pack_from_clip` 建完包就把 clip id 丢了，
-- `asset_packs.source='v2v'` 只说明「这个包来自视频流水线」，说不出是哪一条。
--
-- 于是「未入资产库」这个筛选做不出来，而它恰恰是成片列唯一的待办：片子做完不入库，
-- 整条发布链就断在这里，且断得毫无声响。
--
-- **不设 FK**（同 0020 work_id、0018 work_exports 的理由）：素材包会被退役、删除，
-- 而那时这条 clip 应当重新变回「尚未入库」而不是连查询都报错。列表查询用
-- `EXISTS(SELECT 1 FROM asset_packs …)` 判定，包没了自然回落成未入库 —— 这正是想要的
-- 语义：入库与否问的是「现在库里有没有」，不是「历史上打过包没有」。
ALTER TABLE v2v_clips ADD COLUMN asset_pack_id INTEGER;
