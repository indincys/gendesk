-- 0028：本地待发队列 —— 「人已放行、但即梦还没有空位」。
--
-- 起因是一次实测事故：一批 9 条一起提交，即梦逐条给了 submit_id（提交侧「成功 9 · 失败 0」），
-- 随后轮询里 8 条回来 `ret=1310, message=ExceedConcurrencyLimit` —— 非 VIP 通道同一时间
-- 只跑 1 条。那 8 条一分钱没扣，却全被记成 `fail(provider)` 躺进「处理异常」，
-- 而它们本该只是「排在后面」。
--
-- 于是这里要区分的是**同一个 `ready` 里的两种东西**：
--   · 还等着人点确认的（`submit_queued_at IS NULL`）
--   · 人已经点过确认、只是被在跑上限挡下来的（有时刻）
--
-- 为什么不新开一个阶段：那八条在 `ready` 时的一切都还成立（可改参数、可退回改写、
-- 可删）。新阶段等于把七态机改成八态，而它们之间唯一的差别只是「有没有人放过行」——
-- 那是一个标记，不是一个阶段。
--
-- 默认 NULL：存量条目全部算「还没人放行」，与事实相符（0028 之前没有这条队列）。
ALTER TABLE v2v_clips ADD COLUMN submit_queued_at INTEGER;
