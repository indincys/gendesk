-- 0032：提示词记下**是哪个 skill 写的**。
--
-- 为什么要有它：`prompts-*` 系列 skill 会越来越多，而它们的产出质量是有差别的。
-- 一批图整体歪掉时，人第一个要问的就是「这批词是哪个 skill 写的」——在这一列出现
-- 之前，这个问题没有任何地方能回答：工单收录走的是 `commit_preview(.., "library")`，
-- 落库之后它与手工导入的提示词一模一样。
--
-- 为什么落在 prompts 而不是 batches：提示词是**词的来源**，而批次只是「这一次拿它
-- 跑了一遍」。同一批词可以被手动再跑一次，那一批仍然是那个 skill 写的词。
--
-- 为什么不复用既有的 `source` 列：它是受控枚举（library / temp_import），管的是
-- 「这条词进库的路径」，而 skill 名是自由文本、可以有很多个。两件事挤进一列之后，
-- 「临时导入的、由某 skill 写的词」就没法表达了。
--
-- NULL = 不知道（手工导入、0032 之前的历史数据、没有声明 skill 的工单）。
-- 界面对 NULL 不显示标 —— 猜一个来源比不说更糟。
ALTER TABLE prompts ADD COLUMN skill TEXT;
